/**
 * Writes src/environments/environment.generated.ts from:
 * 1) process.env (Docker ENV / CI — wins)
 * 2) merged .env files: repo root ../.env, then frontend/.env (only non-empty keys override)
 *
 * Never use dotenv.config({ override: true }) — an empty PAYPAL_CLIENT_ID= in frontend/.env
 * must not wipe a value from root .env or Docker.
 */
const path = require('path');
const fs = require('fs');
const dotenv = require('dotenv');

const root = path.resolve(__dirname, '..');
const repoRootEnv = path.join(root, '..', '.env');
const frontendEnv = path.join(root, '.env');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  try {
    return dotenv.parse(fs.readFileSync(filePath, 'utf8'));
  } catch {
    return {};
  }
}

/** Later object only applies a key if its value is non-empty after trim. */
function mergePreferNonEmpty(base, over) {
  const out = { ...base };
  for (const [k, v] of Object.entries(over)) {
    if (String(v ?? '').trim() !== '') out[k] = String(v).trim();
  }
  return out;
}

const repoParsed = parseEnvFile(repoRootEnv);
const frontParsed = parseEnvFile(frontendEnv);
const merged = mergePreferNonEmpty(repoParsed, frontParsed);

/**
 * Docker/CI first, then merged files. Empty string in process.env is skipped so a missing
 * ARG does not block file-based values.
 */
function envResolve(key) {
  const pe = process.env[key];
  if (pe !== undefined && String(pe).trim() !== '') return String(pe).trim();
  const me = merged[key];
  if (me !== undefined && String(me).trim() !== '') return String(me).trim();
  return undefined;
}

const apiUrl =
  envResolve('NG_API_URL') ||
  envResolve('FRONTEND_API_URL') ||
  'http://localhost:3000/api';

let umamiScriptUrl = envResolve('UMAMI_SCRIPT_URL') || '';
const umamiHost = (envResolve('UMAMI_HOST_URL') || 'https://umami.showbk.com').replace(/\/$/, '');
if (!umamiScriptUrl && umamiHost) {
  umamiScriptUrl = `${umamiHost}/script.js`;
}

const umamiWebsiteId =
  envResolve('UMAMI_WEBSITE_ID') || '14cabb5c-7310-487f-96a6-05ce09f6005e';

const rawSandbox = envResolve('PAYPAL_USE_SANDBOX');
const useSandbox =
  rawSandbox === undefined ? true : rawSandbox.toLowerCase() === 'true';
const liveId = envResolve('PAYPAL_CLIENT_ID') || '';
const sandboxId = envResolve('PAYPAL_SANDBOX_CLIENT_ID') || '';
const paypalClientId = useSandbox ? sandboxId || liveId : liveId || sandboxId;

if (!paypalClientId) {
  console.warn(
    '[generate-env] PAYPAL_CLIENT_ID is empty — set PAYPAL_CLIENT_ID (or sandbox id) in repo-root .env, frontend/.env, or Docker build args.',
  );
}

const outPath = path.join(root, 'src', 'environments', 'environment.generated.ts');
const content = `/* eslint-disable */
// Generated by scripts/generate-env.cjs — do not edit by hand
export const envGenerated = {
  apiUrl: ${JSON.stringify(apiUrl)},
  umamiScriptUrl: ${JSON.stringify(umamiScriptUrl)},
  umamiWebsiteId: ${JSON.stringify(umamiWebsiteId)},
  paypalClientId: ${JSON.stringify(paypalClientId)},
};
`;

fs.writeFileSync(outPath, content, 'utf8');
console.log('[generate-env] wrote', path.relative(root, outPath));
