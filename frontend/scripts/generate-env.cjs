/**
 * Reads frontend/.env and writes src/environments/environment.generated.ts.
 * Run automatically via prestart / prebuild, or: npm run env
 *
 * Umami script URL: set UMAMI_SCRIPT_URL, or UMAMI_HOST_URL (default https://umami.showbk.com) + /script.js
 * PayPal client id: PAYPAL_CLIENT_ID or PAYPAL_SANDBOX_CLIENT_ID depending on PAYPAL_USE_SANDBOX
 */
const path = require('path');
const fs = require('fs');

const root = path.resolve(__dirname, '..');
const repoRootEnv = path.join(root, '..', '.env');
const frontendEnv = path.join(root, '.env');
const dotenv = require('dotenv');

// Repo root .env (docker-compose / API) then frontend/.env — same keys as backend for PayPal
if (fs.existsSync(repoRootEnv)) {
  dotenv.config({ path: repoRootEnv });
}
if (fs.existsSync(frontendEnv)) {
  dotenv.config({ path: frontendEnv, override: true });
}
// Existing process.env (e.g. Docker ENV from ARG) is not overridden by dotenv

const apiUrl =
  process.env.NG_API_URL?.trim() ||
  process.env.FRONTEND_API_URL?.trim() ||
  'http://localhost:3000/api';

let umamiScriptUrl = process.env.UMAMI_SCRIPT_URL?.trim() || '';
const umamiHost = (process.env.UMAMI_HOST_URL || 'https://umami.showbk.com').replace(/\/$/, '');
if (!umamiScriptUrl && umamiHost) {
  umamiScriptUrl = `${umamiHost}/script.js`;
}

const umamiWebsiteId =
  process.env.UMAMI_WEBSITE_ID?.trim() || '14cabb5c-7310-487f-96a6-05ce09f6005e';

const rawSandbox = process.env.PAYPAL_USE_SANDBOX;
const useSandbox =
  rawSandbox === undefined || String(rawSandbox).trim() === ''
    ? true
    : String(rawSandbox).toLowerCase().trim() === 'true';
const liveId = (process.env.PAYPAL_CLIENT_ID || '').trim();
const sandboxId = (process.env.PAYPAL_SANDBOX_CLIENT_ID || '').trim();
/** Prefer the id matching PAYPAL_USE_SANDBOX, fall back to the other so .env typos still load a client id */
const paypalClientId = useSandbox ? sandboxId || liveId : liveId || sandboxId;

const outPath = path.join(root, 'src', 'environments', 'environment.generated.ts');
const content = `/* eslint-disable */
// Generated by scripts/generate-env.cjs from frontend/.env — do not edit by hand
export const envGenerated = {
  apiUrl: ${JSON.stringify(apiUrl)},
  umamiScriptUrl: ${JSON.stringify(umamiScriptUrl)},
  umamiWebsiteId: ${JSON.stringify(umamiWebsiteId)},
  paypalClientId: ${JSON.stringify(paypalClientId)},
};
`;

fs.writeFileSync(outPath, content, 'utf8');
console.log('[generate-env] wrote', path.relative(root, outPath));
